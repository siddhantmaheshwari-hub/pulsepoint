import type { ReactNode } from 'react';
import { SOURCE_LABEL, type SourceId } from '@/lib/types';

export function AiMark({ label = 'AI reading' }: { label?: string }) {
  return <span className="ai-mark" title="Interpretation generated by Gemini Flash from the linked evidence"><svg width="9" height="9" viewBox="0 0 10 10" aria-hidden="true"><path d="M5 0l1.3 3.7L10 5 6.3 6.3 5 10 3.7 6.3 0 5l3.7-1.3z" fill="currentColor" /></svg>{label}</span>;
}

const SRC_STYLE: Record<SourceId, string> = { hackernews: 'bg-[#FBE9DD] text-[#9A4A1C]', stackoverflow: 'bg-[#FCEFD6] text-[#8A5A0B]', github: 'bg-sunk text-ink-2' };
const SRC_SHORT: Record<SourceId, string> = { hackernews: 'HN', stackoverflow: 'SO', github: 'GH' };
export function SourceChip({ id, full = false }: { id: SourceId; full?: boolean }) {
  return <span className={`tag h-5 px-2 text-[11px] ${SRC_STYLE[id]}`} title={SOURCE_LABEL[id]}>{full ? SOURCE_LABEL[id] : SRC_SHORT[id]}<span className="sr-only">{full ? '' : ` ${SOURCE_LABEL[id]}`}</span></span>;
}

export function Metric({ value, label, sub, accent }: { value: ReactNode; label: string; sub?: ReactNode; accent?: string }) {
  return (
    <div className="min-w-0">
      <p className="text-numeral font-light" style={accent ? { color: accent } : undefined}>{value}</p>
      <p className="mt-2 text-[13px] font-medium text-ink-2">{label}</p>
      {sub && <p className="mt-0.5 text-xs text-ink-muted">{sub}</p>}
    </div>
  );
}

export function PageHeader({ title, lead, children }: { title: string; lead?: ReactNode; children?: ReactNode }) {
  return (
    <div className="mb-8 flex flex-wrap items-end justify-between gap-4">
      <div className="max-w-2xl">
        <h1 className="text-[34px] font-semibold leading-[1.1] tracking-[-0.025em]">{title}</h1>
        {lead && <p className="mt-2.5 text-[15px] leading-relaxed text-ink-muted">{lead}</p>}
      </div>
      {children && <div className="flex flex-wrap items-center gap-2">{children}</div>}
    </div>
  );
}

export function Empty({ title, children, action }: { title: string; children?: ReactNode; action?: ReactNode }) {
  return (
    <div className="rounded-panel border border-dashed border-line-strong px-6 py-10 text-center">
      <p className="text-[15px] font-semibold">{title}</p>
      {children && <div className="mx-auto mt-1.5 max-w-md text-sm text-ink-muted">{children}</div>}
      {action && <div className="mt-4 flex justify-center">{action}</div>}
    </div>
  );
}

const SUFF: Record<string, { label: string; cls: string; tip: string }> = {
  sufficient: { label: 'Solid data', cls: 'text-ink-2', tip: '8+ discussions across both weeks from 2+ sources' },
  limited: { label: 'Limited data', cls: 'text-ink-muted', tip: 'Fewer than 8 discussions, or a single source' },
  insufficient: { label: 'Anecdotal', cls: 'text-fresh', tip: 'Fewer than 3 discussions across both weeks — treat as a lead' },
};
export function Sufficiency({ value }: { value: string }) {
  const s = SUFF[value] ?? SUFF.limited;
  return <span className={`text-xs ${s.cls}`} title={s.tip}>{s.label}</span>;
}
